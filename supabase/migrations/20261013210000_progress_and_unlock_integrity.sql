-- Enforce the learning hierarchy and persist learner progress/unlocks.
-- Existing foreign keys already use ON DELETE RESTRICT; NOT NULL closes the orphan-by-NULL gap.

ALTER TABLE public.lessons
    ALTER COLUMN theme_id SET NOT NULL;

ALTER TABLE public.exercises
    ALTER COLUMN lesson_id SET NOT NULL;

CREATE TABLE public.lesson_progress (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES public.user_profiles(id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    lesson_id bigint NOT NULL REFERENCES public.lessons(id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    status text NOT NULL DEFAULT 'not_started'
        CHECK (status IN ('not_started', 'in_progress', 'completed')),
    progress_percent smallint NOT NULL DEFAULT 0
        CHECK (progress_percent BETWEEN 0 AND 100),
    score_percent smallint
        CHECK (score_percent BETWEEN 0 AND 100),
    attempt_count integer NOT NULL DEFAULT 0
        CHECK (attempt_count >= 0),
    started_at timestamptz,
    completed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT lesson_progress_user_lesson_key UNIQUE (user_id, lesson_id)
);

COMMENT ON TABLE public.lesson_progress IS
    'Per-user progress state for each lesson. Writes are server-controlled.';
COMMENT ON COLUMN public.lesson_progress.progress_percent IS
    'Completion percentage from 0 to 100.';
COMMENT ON COLUMN public.lesson_progress.score_percent IS
    'Optional latest score percentage from 0 to 100.';

CREATE TABLE public.content_unlocks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES public.user_profiles(id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    catalogue_id bigint REFERENCES public.catalogues(id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    theme_id bigint REFERENCES public.themes(id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    lesson_id bigint REFERENCES public.lessons(id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    unlocked_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT content_unlocks_exactly_one_target CHECK (
        num_nonnulls(catalogue_id, theme_id, lesson_id) = 1
    )
);

COMMENT ON TABLE public.content_unlocks IS
    'Per-user content unlocks for catalogues, themes, or lessons. Writes are server-controlled.';

CREATE UNIQUE INDEX content_unlocks_user_catalogue_key
    ON public.content_unlocks (user_id, catalogue_id)
    WHERE catalogue_id IS NOT NULL;
CREATE UNIQUE INDEX content_unlocks_user_theme_key
    ON public.content_unlocks (user_id, theme_id)
    WHERE theme_id IS NOT NULL;
CREATE UNIQUE INDEX content_unlocks_user_lesson_key
    ON public.content_unlocks (user_id, lesson_id)
    WHERE lesson_id IS NOT NULL;

CREATE INDEX lesson_progress_lesson_id_idx
    ON public.lesson_progress (lesson_id);
CREATE INDEX content_unlocks_catalogue_id_idx
    ON public.content_unlocks (catalogue_id)
    WHERE catalogue_id IS NOT NULL;
CREATE INDEX content_unlocks_theme_id_idx
    ON public.content_unlocks (theme_id)
    WHERE theme_id IS NOT NULL;
CREATE INDEX content_unlocks_lesson_id_idx
    ON public.content_unlocks (lesson_id)
    WHERE lesson_id IS NOT NULL;

CREATE TRIGGER handle_updated_at
    BEFORE UPDATE ON public.lesson_progress
    FOR EACH ROW EXECUTE FUNCTION extensions.moddatetime('updated_at');

ALTER TABLE public.lesson_progress ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.content_unlocks ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can read their own lesson progress"
    ON public.lesson_progress
    FOR SELECT TO authenticated
    USING (user_id = (SELECT auth.uid()));

CREATE POLICY "Users can read their own content unlocks"
    ON public.content_unlocks
    FOR SELECT TO authenticated
    USING (user_id = (SELECT auth.uid()));

REVOKE ALL ON TABLE public.lesson_progress, public.content_unlocks FROM anon;
REVOKE ALL ON TABLE public.lesson_progress, public.content_unlocks FROM authenticated;
GRANT SELECT ON TABLE public.lesson_progress, public.content_unlocks TO authenticated;
GRANT ALL ON TABLE public.lesson_progress, public.content_unlocks TO service_role;
GRANT ALL ON SEQUENCE public.lesson_progress_id_seq, public.content_unlocks_id_seq TO service_role;
